#ifndef FUNCTION_H
#define FUNCTION_H

/******************************************************************************
 * 文件：function.hpp
 * 作用：与 bin 帧头时间戳解码有关的底层工具。
 * 背景：帧头里的 date / time 是【BCD 打包】的 32 位整数，
 *       不是普通二进制整数，不能直接当数值用，必须按 BCD 规则拆字节。
 *       例：0x20240929 表示 2024 年 09 月 29 日；0x14412900 表示 14:41:29。
 ******************************************************************************/

#include <stdio.h>
#include <stdint.h>

/**************************一、解码目标枚举*************************/

/* 决定 bcd_date_to_integer 走哪个分支、返回什么格式 */
enum datetime
{
    Date,             /* 按日期解：返回 YYYYMMDD 十进制整数，如 20261107 */
    Time_tatol,       /* 按时分秒解：返回当日累计总秒数，如 14:41:29 → 52889 */
    Time_intuitive    /* 按时分秒解：返回 HHMMSS 十进制整数，如 14:41:29 → 144129 */
    
};

/**************************二、对外接口*************************/

//将打包为BCD格式的32bit日期原始值，转为十进制整数
uint64_t bcd_date_to_integer(uint32_t raw_date,datetime dt);

#endif // !FUNCTION_H
